#!/usr/bin/env python3
"""Generate sushi-webui-go-mods.inc from a sushi-webui checkout.

Scarthgap's bitbake (2.8) has no gomod:// fetcher, so each Go module listed in
go.mod is fetched as its .info/.mod/.zip triplet from the Go module proxy and
pinned with a sha256. The recipe lays them out as a file:// GOPROXY.

Usage: update-go-mods.py <sushi-webui checkout> [output .inc]

Rerun whenever go.mod changes (i.e. when bumping SRCREV).
"""
import hashlib
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

PROXY = "https://proxy.golang.org"
EXTS = ("info", "mod", "zip")


def escape(path):
    """Go module proxy case-encoding: uppercase letters become !lowercase."""
    return re.sub(r"[A-Z]", lambda m: "!" + m.group(0).lower(), path)


def parse_requires(go_mod):
    mods, in_block = [], False
    for line in go_mod.read_text().splitlines():
        line = line.split("//")[0].strip()
        if line == "require (":
            in_block = True
        elif in_block and line == ")":
            in_block = False
        elif in_block and line:
            mods.append(tuple(line.split()[:2]))
        elif line.startswith("require ") and "(" not in line:
            mods.append(tuple(line.split()[1:3]))
    return mods


def fetch_sha256(url):
    with urllib.request.urlopen(url, timeout=120) as r:
        return hashlib.sha256(r.read()).hexdigest()


def main():
    repo = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("sushi-webui-go-mods.inc")
    rev = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                         capture_output=True, text=True).stdout.strip()
    mods = parse_requires(repo / "go.mod")

    lines = [
        f"# Generated by update-go-mods.py from sushi-webui go.mod @ {rev}.",
        "# Do not edit by hand; rerun the script when go.mod changes.",
        "",
        'GO_MODULES = "\\',
    ]
    srcuri, sums = [], []
    for i, (path, ver) in enumerate(mods):
        esc = escape(path)
        lines.append(f"    {esc}@{ver} \\")
        flat = esc.replace("/", "__")
        for ext in EXTS:
            name = f"gomod{i}-{ext}"
            url = f"{PROXY}/{esc}/@v/{ver}.{ext}"
            fname = f"gomod__{flat}__{ver}.{ext}"
            srcuri.append(f"    {url};downloadfilename={fname};unpack=0;name={name} \\")
            sums.append(f'SRC_URI[{name}.sha256sum] = "{fetch_sha256(url)}"')
            print(f"{path}@{ver}.{ext}", file=sys.stderr)
    lines += ['"', "", 'SRC_URI += "\\', *srcuri, '"', "", *sums, ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(mods)} modules)", file=sys.stderr)


if __name__ == "__main__":
    main()
