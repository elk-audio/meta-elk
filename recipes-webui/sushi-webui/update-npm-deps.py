#!/usr/bin/env python3
"""Generate sushi-webui-npm-deps.inc from the npm shrinkwrap.

Wrynose's bitbake has disabled the npmsw fetcher, so every package of the
lockfile is fetched as a plain tarball, pinned by the sha512 integrity of the
lockfile, and unpacked into node_modules by sushi-webui-frontend-native.

usage: update-npm-deps.py files/npm-shrinkwrap.json sushi-webui-npm-deps.inc
"""
import base64
import json
import sys
from pathlib import Path


def wanted(pkg):
    """Optional platform packages are only needed for the build host: linux x64 (glibc)."""
    if not pkg.get("optional"):
        return True
    return (pkg.get("os") in (None, ["linux"]) and pkg.get("cpu") in (None, ["x64"])
            and pkg.get("libc") in (None, ["glibc"]))


def main():
    lock = Path(sys.argv[1])
    out = Path(sys.argv[2])
    packages = json.loads(lock.read_text())["packages"]

    entries = []
    for path, pkg in sorted(packages.items()):
        if path and wanted(pkg):
            entries.append((path, pkg))

    uris = []
    sums = []
    files = []
    for i, (path, pkg) in enumerate(entries):
        url = pkg["resolved"]
        algo, _, b64 = pkg["integrity"].partition("-")
        assert algo == "sha512", (path, algo)
        flat = url.split("registry.npmjs.org/", 1)[1].replace("/-/", "__").replace("/", "__")
        files.append(f"    {path}=npm__{flat} \\")
        uris.append(f"    {url};downloadfilename=npm__{flat};unpack=0;name=npm{i} \\")
        sums.append(f'SRC_URI[npm{i}.sha512sum] = "{base64.b64decode(b64).hex()}"')

    lines = [
        f"# Generated by update-npm-deps.py from {lock.name}.",
        "# Do not edit by hand; rerun the script when the shrinkwrap changes.",
        "",
        'NPM_PACKAGES = "\\',
        *files,
        '"',
        "",
        'SRC_URI += "\\',
        *uris,
        '"',
        "",
        *sums,
        "",
    ]
    out.write_text("\n".join(lines))


main()
